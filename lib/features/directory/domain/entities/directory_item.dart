class DirectoryItem {
  final int id;
  final String name;
  final String category;
  final String phone;
  final String city;
  final String address;
  final double rating;

  DirectoryItem({
    required this.id,
    required this.name,
    required this.category,
    required this.phone,
    required this.city,
    required this.address,
    required this.rating,
  });
}
